"""Reset build-generated keys and integrity hashes before publication.

This intentionally makes encrypted archive decryption fail closed until the
normal key and hash injection steps are run for a private build.
"""

import re
import sys
from pathlib import Path


REPLACEMENTS = (
    (
        r"(    // KEY_RECOVER_BEGIN\r?\n).*?(    // KEY_RECOVER_END)",
        r"\1    memset(out, 0, 32); /* Build-time placeholder. */\n\2",
    ),
    (
        r"(    // HASH_COMPARE_BEGIN\r?\n).*?(    // HASH_COMPARE_END)",
        r"\1    ok = 0; /* Build-time placeholder: fail closed. */\n\2",
    ),
    (
        r"(    // CODE_WHITELIST_BEGIN\r?\n).*?(    // CODE_WHITELIST_END)",
        r"\1    // Generated by scripts/inject_code_hash.py for private builds.\n"
        r"    {0u, 0u, 0u}, /* Build-time placeholder: no caller matches. */\n\2",
    ),
    (
        r"(                    // CODE_HASH_BEGIN\r?\n).*?(                    // CODE_HASH_END)",
        r"\1                    /* Generated by scripts/inject_code_hash.py. */\n\2",
    ),
)


def reset(path: Path) -> None:
    source = path.read_text(encoding="utf-8")
    source, macro_count = re.subn(
        r"#define AES_KEY_INJECTED [01]",
        "#define AES_KEY_INJECTED 0",
        source,
        count=1,
    )

    if macro_count != 1:
        raise SystemExit("AES_KEY_INJECTED marker not found")

    for pattern, replacement in REPLACEMENTS:
        source, count = re.subn(pattern, replacement, source, count=1, flags=re.DOTALL)
        if count != 1:
            raise SystemExit(f"Expected one generated region for pattern: {pattern}")

    path.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) == 2 else Path("src/aes_rpa.c")
    reset(target)
    print(f"Reset generated security data in {target}")
